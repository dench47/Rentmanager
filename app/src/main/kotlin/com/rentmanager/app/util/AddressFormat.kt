package com.rentmanager.app.util

/**
 * Короткий адрес для отображения: первые два сегмента полной строки
 * (улица и номер дома) — тот же формат, что в списке «Моя недвижимость».
 * Применяется только в отображении, НЕ в полях редактирования — иначе
 * сохранение затрёт полный адрес короткой версией.
 */
fun String.shortAddress(): String =
    split(',').map { it.trim() }.filter { it.isNotEmpty() }.take(2).joinToString(", ")
